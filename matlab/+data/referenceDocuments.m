function docs = referenceDocuments()
%REFERENCEDOCUMENTS  Every document this tool's numbers rest on.
%   docs = data.referenceDocuments() returns a struct array, one row per
%   document, with the citation, what the tool takes from it, and the file
%   name a local copy would have.
%
%   WHY A LIST AND NOT A BUNDLE. The Help menu was specified as "opening
%   the bundled PDFs" (GUI2_SPEC.md Sec. 3). It cannot be. Nine of these
%   documents are not ours to redistribute -- every NAS/NASM sheet carries
%   "COPYRIGHT ... Aerospace Industries Association ... ALL RIGHTS
%   RESERVED", the DABJ course book carries a copyright notice and
%   restrictions, and the Heli-Coil bulletin is vendor material -- and
%   references/ is gitignored twice over precisely so none of them can be
%   published by accident. Shipping them inside a distributed .exe would
%   be an infringement, and the copyrighted ones are exactly the sheets
%   the hardware catalogue is transcribed from.
%
%   So the tool ships the CITATIONS, which are facts and are the part that
%   carries traceability, and opens a local copy only where the analyst
%   already has one. An analyst asking "where did this allowable come
%   from?" gets an answer either way; only the convenience of the click
%   depends on the file being present.
%
%   HEADLESS ON PURPOSE. gui2.ReferencesView renders this, but the list is
%   data rather than layout: it is the single place the citations live, it
%   is testable without building a GUI, and a report could use it too.
%
%   Fields:
%     Key             short id, stable across renames of the file
%     Title           document title as printed on it
%     Publisher       issuing body
%     Year            edition/revision year as a string ("" if not dated)
%     Role            "Governing" | "Supplemental" | "Hardware data" |
%                     "Validation" | "Background"
%     UsedFor         what THIS tool takes from it, in one line
%     File            expected file name of a local copy ("" if none)
%     Redistributable logical -- may this ship inside the packaged tool
%
%   ROLE FOLLOWS CLAUDE.md's DOCUMENT HIERARCHY, and the distinction is
%   not cosmetic: NASA-STD-5020B governs; a supplement is cited only where
%   5020B itself relies on it for a formula it does not print; and the
%   DABJ course book is VALIDATION ONLY and must never be cited as a
%   governing equation. A reader of this list should be able to see that
%   ordering without knowing the rule already.
%
%   Tests: tests/tReferenceDocuments.m.

