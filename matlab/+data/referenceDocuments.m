% ---- Local helpers --------------------------------------------------------
function d = row(key, title, publisher, year, role, usedFor, file, redist)
%ROW  One reference document.
d = struct( ...
    "Key",             string(key), ...
    "Title",           string(title), ...
    "Publisher",       string(publisher), ...
    "Year",            string(year), ...
    "Role",            string(role), ...
    "UsedFor",         string(usedFor), ...
    "File",            string(file), ...
    "Redistributable", logical(redist));
